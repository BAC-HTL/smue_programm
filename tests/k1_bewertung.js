// Testklassen für die Bewertungslogik (ohne Browser)
const C = require('../src/core.js');
const { fall, klasse } = require('./hilfsmittel');
const text = (acc, o) => Object.assign({ type: 'text', points: 1, accepted: acc }, o);
const zahl = (v, o) => Object.assign({ type: 'number', points: 1, value: v, tol: '', unit: '' }, o);
const multi = (pts, r, f) => ({ type: 'multi', points: pts, options: [...Array(r).fill(0).map((_, i) => ({ text: 'R' + i, correct: true })), ...Array(f).fill(0).map((_, i) => ({ text: 'F' + i, correct: false }))] });
const e = (q, a) => C.grade(q, a).earned;
const st = (q, a) => C.grade(q, a).status;

module.exports = async function () {
  klasse('T1 Kurzantwort');
  await fall('ÄK-T01', 'Gültig: exakt richtig', 1, () => e(text(['Wien']), 'Wien'));
  await fall('ÄK-T02', 'Gültig: andere Groß-/Kleinschreibung ohne Option', 1, () => e(text(['Wien']), 'wIEN'));
  await fall('ÄK-T03', 'Gültig: zweite erlaubte Antwort', 1, () => e(text(['Rad', 'Fahrrad']), 'fahrrad'));
  await fall('ÄK-T04', 'Ungültig: falsche Antwort', 0, () => e(text(['Wien']), 'Graz'));
  await fall('ÄK-T05', 'Ungültig: Schreibung falsch bei Option Groß/Klein', 0, () => e(text(['Wien'], { caseSensitive: true }), 'wien'));
  await fall('ÄK-T06', 'Leer: nichts eingegeben gilt als unbeantwortet', 'empty', () => st(text(['Wien']), ''));
  await fall('ÄK-T07', 'Leer: nur Leerzeichen gilt als unbeantwortet', 'empty', () => st(text(['Wien']), '   '));
  await fall('ÄK-T08', 'Gültig: Leerzeichen außen und doppelt innen', 1, () => e(text(['New York']), '  new   york '));
  await fall('ÄK-T09', 'Gültig: gleicher Text in anderer Unicode-Form (ü zerlegt)', 1, () => e(text(['Müller']), 'Müller'));
  await fall('ÄK-T10', 'Ungültig: ß und ss sind verschieden', 0, () => e(text(['Straße']), 'Strasse'));
  await fall('ÄK-T11', 'Gültig: typografischer Apostroph', 1, () => e(text(["it's"]), 'it’s'));
  await fall('GW-T01', 'Tippfehler: Antwort mit 4 Zeichen, keine Toleranz', 0, () => e(text(['Wien'], { typo: true }), 'Wein'));
  await fall('GW-T02', 'Tippfehler: Antwort mit 5 Zeichen, 1 Fehler zählt', 1, () => e(text(['Linde'], { typo: true }), 'Linda'));
  await fall('GW-T03', 'Tippfehler: 5 Zeichen, 2 Fehler zählen nicht', 0, () => e(text(['Linde'], { typo: true }), 'Landa'));
  await fall('GW-T04', 'Tippfehler: 1 Buchstabe fehlt', 1, () => e(text(['Innsbruck'], { typo: true }), 'Innsbruk'));
  await fall('GW-T05', 'Tippfehler: 2 Buchstaben fehlen', 0, () => e(text(['Innsbruck'], { typo: true }), 'Insbruk'));
  await fall('GW-T06', 'Antwort mit 10.000 Zeichen', 0, () => e(text(['Wien']), 'x'.repeat(10000)));
  await fall('GW-T07', 'Antwort mit genau 1 Zeichen', 1, () => e(text(['A']), 'a'));

  klasse('T2 Zahlen');
  await fall('ÄK-Z01', 'Gültig: ganze Zahl', 1, () => e(zahl('9'), '9'));
  await fall('ÄK-Z02', 'Gültig: Komma statt Punkt', 1, () => e(zahl('3.5'), '3,5'));
  await fall('ÄK-Z03', 'Gültig: Punkt statt Komma', 1, () => e(zahl('3,5'), '3.5'));
  await fall('ÄK-Z04', 'Gültig: Bruch', 1, () => e(zahl('0,75'), '3/4'));
  await fall('ÄK-Z05', 'Gültig: negativer Bruch', 1, () => e(zahl('-0,75'), '-3/4'));
  await fall('ÄK-Z06', 'Gültig: Tausenderpunkt', 1, () => e(zahl('1000'), '1.000'));
  await fall('ÄK-Z07', 'Gültig: Tausenderpunkt mit Komma', 1, () => e(zahl('1234,5'), '1.234,5'));
  await fall('ÄK-Z08', 'Gültig: Leerzeichen als Tausendertrenner', 1, () => e(zahl('1000000'), '1 000 000'));
  await fall('ÄK-Z09', 'Gültig: Einheit mitgetippt', 1, () => e(zahl('9', { unit: 'km' }), '9 km'));
  await fall('ÄK-Z10', 'Gültig: Einheit ohne Abstand, anders geschrieben', 1, () => e(zahl('9', { unit: 'km' }), '9KM'));
  await fall('ÄK-Z11', 'Gültig: Minuszeichen aus dem Zeichensatz', 1, () => e(zahl('-5'), '−5'));
  await fall('ÄK-Z12', 'Ungültig: Wort statt Zahl', 0, () => e(zahl('9'), 'neun'));
  await fall('ÄK-Z13', 'Ungültig: falsche Einheit', 0, () => e(zahl('9', { unit: 'km' }), '9 m'));
  await fall('ÄK-Z14', 'Ungültig: wissenschaftliche Schreibweise wird nicht erkannt', 0, () => e(zahl('1000'), '1e3'));
  await fall('ÄK-Z15', 'Ungültig: zwei Kommas', 0, () => e(zahl('1'), '1,5,5'));
  await fall('ÄK-Z16', 'Ungültig: Division durch 0', 0, () => e(zahl('0'), '3/0'));
  await fall('ÄK-Z17', 'Punkt als Dezimalzeichen mit 3 Stellen: 1.234 bei Lösung 1,234', 1, () => e(zahl('1,234'), '1.234'));
  await fall('GW-Z01', 'Null', 1, () => e(zahl('0'), '0'));
  await fall('GW-Z02', 'Minus null gleich null', 1, () => e(zahl('0'), '-0'));
  await fall('GW-Z03', 'Ohne führende Null', 1, () => e(zahl('0,5'), ',5'));
  await fall('GW-Z04', 'Abschließendes Komma', 1, () => e(zahl('5'), '5,'));
  await fall('GW-Z05', 'Toleranz 0,1: genau untere Grenze 9,9', 1, () => e(zahl('10', { tol: '0,1' }), '9,9'));
  await fall('GW-Z06', 'Toleranz 0,1: genau obere Grenze 10,1', 1, () => e(zahl('10', { tol: '0,1' }), '10,1'));
  await fall('GW-Z07', 'Toleranz 0,1: knapp darunter 9,8999', 0, () => e(zahl('10', { tol: '0,1' }), '9,8999'));
  await fall('GW-Z08', 'Toleranz 0,1: knapp darüber 10,1001', 0, () => e(zahl('10', { tol: '0,1' }), '10,1001'));
  await fall('GW-Z09', 'Toleranz 0: kleinste Abweichung zählt nicht', 0, () => e(zahl('1'), '1,000001'));
  await fall('GW-Z10', 'Sehr große Zahl, 15 Stellen', 1, () => e(zahl('123456789012345'), '123456789012345'));
  await fall('GW-Z11', 'Sehr kleine Zahl', 1, () => e(zahl('0,000001'), '0,000001'));
  await fall('GW-Z12', 'Summe mit Rundungsproblem 0,1 + 0,2', 1, () => e(zahl('0,3', { tol: '0' }), String(0.1 + 0.2).replace('.', ',')));

  klasse('T3 Mehrfachauswahl und Teilpunkte');
  await fall('ÄK-M01', 'Alle richtigen angekreuzt', 3, () => e(multi(3, 3, 2), [0, 1, 2]));
  await fall('ÄK-M02', 'Teilweise richtig', 2, () => e(multi(3, 3, 2), [0, 1]));
  await fall('ÄK-M03', 'Richtige und eine falsche', 1, () => e(multi(3, 3, 2), [0, 1, 3]));
  await fall('ÄK-M04', 'Nur falsche', 0, () => e(multi(3, 3, 2), [3, 4]));
  await fall('ÄK-M05', 'Alles angekreuzt', 1, () => e(multi(3, 3, 2), [0, 1, 2, 3, 4]));
  await fall('ÄK-M06', 'Nichts angekreuzt', 'empty', () => st(multi(3, 3, 2), []));
  await fall('GW-M01', 'Punkte fallen nie unter 0', 0, () => e(multi(3, 1, 4), [0, 1, 2, 3, 4]));
  await fall('GW-M02', 'Teilpunkt 1/3 von 1 Punkt wird 0,5', 0.5, () => e(multi(1, 3, 0), [0]));
  await fall('GW-M03', 'Teilpunkt 1/4 von 1 Punkt wird 0,5', 0.5, () => e(multi(1, 4, 0), [0]));
  await fall('GW-M04', 'Teilpunkt 1/5 von 1 Punkt wird 0', 0, () => e(multi(1, 5, 0), [0]));
  await fall('GW-M05', 'Unvollständig darf nie die volle Punktzahl geben: 4 von 5 bei 1 Punkt', 0.5, () => e(multi(1, 5, 0), [0, 1, 2, 3]));
  await fall('GW-M06', 'Unvollständig gilt nie als richtig: Status bei 4 von 5', 'partial', () => st(multi(1, 5, 0), [0, 1, 2, 3]));
  await fall('GW-M07', 'Antwortindex außerhalb der Liste wird ignoriert', 0, () => e(multi(1, 1, 1), [99]));

  klasse('T4 Lückentext');
  const l = (p, pts = 2, o) => Object.assign({ type: 'cloze', prompt: p, points: pts }, o);
  await fall('ÄK-L01', 'Alle Lücken richtig', 2, () => e(l('{a} {b}'), ['a', 'b']));
  await fall('ÄK-L02', 'Eine von zwei Lücken richtig', 1, () => e(l('{a} {b}'), ['a', 'x']));
  await fall('ÄK-L03', 'Alternative Lösung', 2, () => e(l('{Rad|Fahrrad} {b}'), ['fahrrad', 'b']));
  await fall('ÄK-L04', 'Falsche Auswahl mit ~ zählt nicht', 0, () => e(l('{a|~b}', 1), ['b']));
  await fall('ÄK-L05', 'Auswahlliste ohne Lösungsverrat: alphabetisch', 'Eisenstadt,Graz,Linz', () => C.choiceList(['Graz'], ['Linz', 'Eisenstadt']).join());
  await fall('ÄK-L06', 'Nur erste richtige Antwort steht in der Liste', 'Fahrrad,Linz', () => C.choiceList(['Fahrrad', 'Rad'], ['Linz']).join());
  await fall('ÄK-L07', 'Keine doppelten Einträge in der Liste', 'Linz,Wien', () => C.choiceList(['Wien'], ['Linz', 'Wien']).join());
  await fall('GW-L01', 'Text ohne Lücke', 0, () => C.gapsOf(l('kein Platzhalter')).length);
  await fall('GW-L02', 'Genau eine Lücke', 1, () => C.gapsOf(l('{a}')).length);
  await fall('GW-L03', '100 Lücken', 100, () => C.gapsOf(l(Array(100).fill('{a}').join(' '))).length);
  await fall('GW-L04', 'Leere Klammer {} ist keine Lücke', 0, () => C.gapsOf(l('{}')).length);
  await fall('GW-L05', 'Klammer mit Leerzeichen hat keine Lösung', 0, () => C.gapsOf(l('{ }'))[0].gap.length);
  await fall('GW-L06', 'Nicht geschlossene Klammer ist keine Lücke', 0, () => C.gapsOf(l('{a')).length);
  await fall('GW-L07', 'Unvollständig darf nie die volle Punktzahl geben: 4 von 5 Lücken bei 1 Punkt', 0.5, () => e(l('{a} {b} {c} {d} {e}', 1), ['a', 'b', 'c', 'd', 'x']));
  await fall('GW-L08', 'Mehr Antworten als Lücken stören nicht', 1, () => e(l('{a}', 1), ['a', 'b', 'c']));

  klasse('T5 Richtig/Falsch und Einfachauswahl');
  const sc = { type: 'single', points: 1, options: [{ text: 'A', correct: false }, { text: 'B', correct: true }] };
  await fall('ÄK-E01', 'Richtig gewählt', 1, () => e(sc, 1));
  await fall('ÄK-E02', 'Falsch gewählt', 0, () => e(sc, 0));
  await fall('ÄK-E03', 'Nichts gewählt', 'empty', () => st(sc, null));
  await fall('GW-E01', 'Index -1', 0, () => e(sc, -1));
  await fall('GW-E02', 'Index hinter der Liste', 0, () => e(sc, 2));
  await fall('ÄK-E04', 'Aussage ist falsch und falsch gewählt', 1, () => e({ type: 'tf', points: 1, answer: false }, false));
  await fall('ÄK-E05', 'Aussage ist richtig und falsch gewählt', 0, () => e({ type: 'tf', points: 1, answer: true }, false));

  klasse('T6 Notenschlüssel');
  const g = { on: true, thresholds: [88, 75, 63, 50] }, n = p => C.gradeLabel(p, g).nr;
  for (const [id, p, w] of [['01', 100, 1], ['02', 88, 1], ['03', 87.9, 2], ['04', 75, 2], ['05', 74.9, 3], ['06', 63, 3], ['07', 62.9, 4], ['08', 50, 4], ['09', 49.9, 5], ['10', 0, 5]])
    await fall('GW-N' + id, p + ' % ergibt Note ' + w, w, () => n(p));
  await fall('ÄK-N01', 'Ohne Notenschlüssel keine Note', 'null', () => String(C.gradeLabel(90, { on: false })));

  klasse('T7 Verschlüsselung der Fragen');
  const roh = o => JSON.stringify(o);
  await fall('ÄK-V01', 'Richtiger Code entschlüsselt', 'true', () => String(roh(C.unseal(C.seal({ a: 1 }, 't', 'X'), 't', 'X')) === roh({ a: 1 })));
  await fall('ÄK-V02', 'Falscher Code liefert nichts', 'null', () => String(C.unseal(C.seal({ a: 1 }, 't', 'X'), 't', 'Y')));
  await fall('ÄK-V03', 'Code ohne Rücksicht auf Groß/Klein und Leerzeichen', 'true', () => String(!!C.unseal(C.seal({ a: 1 }, 't', 'Ab12'), 't', '  aB12 ')));
  await fall('ÄK-V04', 'Umlaute, Griechisch, Kyrillisch, Emoji bleiben erhalten', 'äß√πЖ😀', () => C.unseal(C.seal({ s: 'äß√πЖ😀' }, 't', ''), 't', '').s);
  await fall('ÄK-V05', 'Beschädigte Daten führen nicht zum Absturz', 'null', () => String(C.unseal('%%%kein-base64', 't', '')));
  await fall('GW-V01', 'Leeres Objekt', '{}', () => roh(C.unseal(C.seal({}, 't', ''), 't', '')));
  await fall('GW-V02', 'Datenmenge 2 MB', 2000000, () => C.unseal(C.seal({ s: 'x'.repeat(2000000) }, 't', ''), 't', '').s.length);
  await fall('GW-V03', 'Code unterscheidet sich im letzten Zeichen', 'null', () => String(C.unseal(C.seal({ a: 1 }, 't', 'CODE1'), 't', 'CODE2')));
  await fall('GW-V04', 'Antworten stehen nicht im Klartext in den Daten', 'false', () => String(Buffer.from(C.seal({ s: 'GEHEIMNIS' }, 't', ''), 'base64').toString('latin1').includes('GEHEIMNIS')));
};
